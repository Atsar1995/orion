/** Maps numeric health score to executive health label. */
export function resolveCustomerHealthLabel(score: number): CustomerHealthLabel {
  if (score >= 90) {
    return "Excellent";
  }

  if (score >= 75) {
    return "Good";
  }

  if (score >= 60) {
    return "Needs Attention";
  }

  return "At Risk";
}

